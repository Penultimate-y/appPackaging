function Get-AppInstaller
{
    <#
    .SYNOPSIS
        Returns a local path to the DLIllustr installer.
    .DESCRIPTION
        Prefers an installer staged in this package's Files folder. When none is present,
        resolves the current vendor download URL and downloads it to the PSADT temp folder.
    .OUTPUTS
        System.String. Full path to the installer on disk.
    #>
    [CmdletBinding()]
    [OutputType([System.String])]
    param ()

    ## Offline path: honour any installer staged in Files\ so the package works air-gapped.
    if ($adtSession.DirFiles -and (Test-Path -LiteralPath $adtSession.DirFiles))
    {
        $staged = Get-ChildItem -LiteralPath $adtSession.DirFiles -File -ErrorAction Ignore |
            Where-Object { $_.Extension -in '.msi', '.exe', '.zip' } |
            Select-Object -First 1

        if ($staged)
        {
            Write-ADTLogEntry -Message "Using installer staged in Files folder: $($staged.FullName)"
            return $staged.FullName
        }
    }

    ## Online path: resolve the current vendor download URL.
    $downloadUrl = $null
    $resolvedVersion = 'Unknown'

    try
    {
        ## This vendor blocks automated downloads, so there is no resolvable URL.
        ## The installer MUST be staged in the package Files folder (checked above).
        $guidance = @(
            'No installer was found in the package Files folder.'
            ''
            'DLIllustr has no automation-friendly public download URL - the vendor blocks'
            'scripted downloads, so this package cannot fetch the installer itself.'
            ''
            'To use this package:'
            '  1. Download DLIllustr manually from: DLIllustr is an internal Delaware Life / Group 1001 illustration tool (DocsCorp DocsCorp-derived InstallShield MSI) with no public download URL. Obtain the current ''DLIllustr v<version>.msi'' from the internal software distribution share and stage it in the package Files folder.'
            '  2. Place the installer in the package Files folder (any .msi, .exe or .zip).'
            '  3. Rebuild the .intunewin and re-upload it to Intune.'
        ) -join [System.Environment]::NewLine
        throw $guidance
    }
    catch
    {
        Write-ADTLogEntry -Message "Failed to resolve the DLIllustr download URL: $($_.Exception.Message)" -Severity 3
        throw
    }

    if ([System.String]::IsNullOrWhiteSpace($downloadUrl))
    {
        throw 'Resolved an empty download URL for DLIllustr.'
    }

    Write-ADTLogEntry -Message "Resolved DLIllustr version: $resolvedVersion"
    Write-ADTLogEntry -Message "Download URL: $downloadUrl"

    ## Download into the PSADT-managed temp folder so the session cleans it up.
    $destinationDir = if ($adtSession.DirSupportFiles) { $adtSession.DirSupportFiles } else { $env:TEMP }
    $installerPath = Join-Path -Path $destinationDir -ChildPath $script:InstallerFileName

    Show-ADTInstallationProgress -StatusMessage 'Downloading DLIllustr...'

    try
    {
        ## TLS 1.2 minimum - some vendor CDNs reject older suites.
        [System.Net.ServicePointManager]::SecurityProtocol = [System.Net.SecurityProtocolType]::Tls12
        Invoke-WebRequest -Uri $downloadUrl -OutFile $installerPath -UseBasicParsing
    }
    catch
    {
        Write-ADTLogEntry -Message "Download failed from $downloadUrl - $($_.Exception.Message)" -Severity 3
        throw
    }

    if (-not (Test-Path -LiteralPath $installerPath))
    {
        throw "Download reported success but no file exists at $installerPath."
    }

    $sizeMb = [System.Math]::Round((Get-Item -LiteralPath $installerPath).Length / 1MB, 2)
    if ($sizeMb -le 0)
    {
        throw "Downloaded installer at $installerPath is zero bytes."
    }

    Write-ADTLogEntry -Message "Download complete: $installerPath ($sizeMb MB)"
    return $installerPath
}


function Install-ADTDeployment
{
    [CmdletBinding()]
    param ()

    ##================================================
    ## MARK: Pre-Install
    ##================================================
    $adtSession.InstallPhase = "Pre-$($adtSession.DeploymentType)"

    ## Show welcome message and close the target application if it is running.
    $saiwParams = @{
        AllowDefer = $true
        DeferTimes = 3
        CheckDiskSpace = $true
        PersistPrompt = $true
    }
    if ($adtSession.AppProcessesToClose.Count -gt 0)
    {
        $saiwParams.Add('CloseProcesses', $adtSession.AppProcessesToClose)
    }
    Show-ADTInstallationWelcome @saiwParams

    Show-ADTInstallationProgress -StatusMessage 'Preparing DLIllustr installation...'


    ##================================================
    ## MARK: Install
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## -------------------------------------------------------------------------
    ## Shared-ProductCode cleanup (DLIllustr collision fix).
    ##
    ## Delaware Life reuses the SAME MSI ProductCode across DLIllustr versions
    ## (confirmed: v3.7.0 and v3.8.0 are both {A1DC44AA-97D8-42DA-876C-19275D3AA52D}).
    ## Because Windows Installer keys everything off ProductCode, a pre-existing
    ## older build (e.g. 3.7.0) makes the 3.8.0 MSI look "already installed" and
    ## can trip the InstallShield downgrade guard (ARPNOMODIFY=1), leaving a stale
    ## uninstall key and a wrong DisplayVersion. Force-remove any prior install of
    ## this ProductCode first so 3.8.0 installs clean.
    ## -------------------------------------------------------------------------
    $dlProductCode = '{A1DC44AA-97D8-42DA-876C-19275D3AA52D}'
    $dlUninstallKeys = @(
        "HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\$dlProductCode"
        "HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\$dlProductCode"
        "HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\InstallShield_$dlProductCode"
    )

    $existing = Get-ADTApplication -ProductCode $dlProductCode -ErrorAction Ignore
    if ($existing)
    {
        foreach ($app in $existing)
        {
            Write-ADTLogEntry -Message "Found prior DLIllustr install sharing the 3.8.0 ProductCode: $($app.DisplayName) $($app.DisplayVersion). Removing before install."
        }
        try
        {
            $null = Start-ADTMsiProcess -Action Uninstall -ProductCode $dlProductCode
        }
        catch
        {
            Write-ADTLogEntry -Message "msiexec uninstall of $dlProductCode failed: $($_.Exception.Message). Continuing to key cleanup." -Severity 2
        }
    }
    else
    {
        Write-ADTLogEntry -Message "No prior install found under ProductCode $dlProductCode."
    }

    ## Remove any stale uninstall/InstallShield keys that a same-ProductCode build
    ## can leave behind, so detection does not read a phantom older version.
    foreach ($key in $dlUninstallKeys)
    {
        if (Test-Path -LiteralPath $key)
        {
            Write-ADTLogEntry -Message "Removing stale uninstall key: $key"
            Remove-Item -LiteralPath $key -Recurse -Force -ErrorAction SilentlyContinue
        }
    }

    ## Acquire the installer (staged file or fresh download).
    $installerPath = Get-AppInstaller

    Show-ADTInstallationProgress -StatusMessage 'Installing DLIllustr...'
    Write-ADTLogEntry -Message "Installing DLIllustr from: $installerPath"

    ## Install the MSI. PSADT appends its own /qn and logging options.
    $null = Start-ADTMsiProcess -Action Install -FilePath $installerPath -AdditionalArgumentList @("ALLUSERS=1")

    ##================================================
    ## MARK: Post-Install
    ##================================================
    $adtSession.InstallPhase = "Post-$($adtSession.DeploymentType)"

    ## Verify the install landed where detection expects it.
    if (Test-AppInstalled)
    {
        Write-ADTLogEntry -Message 'DLIllustr installation verified successfully.'
    }
    else
    {
        Write-ADTLogEntry -Message 'DLIllustr installer completed but post-install verification failed.' -Severity 3
        throw 'DLIllustr post-install verification failed. Review the log and the vendor silent-install switches.'
    }

    if ($adtSession.DeployMode -ne 'Silent')
    {
        Show-ADTInstallationPrompt -Message 'DLIllustr has been installed successfully.' -ButtonRightText 'OK' -NoWait
    }
}


function Uninstall-ADTDeployment
{
    [CmdletBinding()]
    param ()

    ##================================================
    ## MARK: Pre-Uninstall
    ##================================================
    $adtSession.InstallPhase = "Pre-$($adtSession.DeploymentType)"

    if ($adtSession.AppProcessesToClose.Count -gt 0)
    {
        Show-ADTInstallationWelcome -CloseProcesses $adtSession.AppProcessesToClose -CloseProcessesCountdown 60
    }

    Show-ADTInstallationProgress -StatusMessage 'Removing DLIllustr...'


    ##================================================
    ## MARK: Uninstall
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## Locate the product in the uninstall registry and run its registered uninstall string.
    $installedApps = Get-ADTApplication -Name '^DLIllustr v' -NameMatch Regex
    if ($installedApps)
    {
        foreach ($app in $installedApps)
        {
            Write-ADTLogEntry -Message "Uninstalling: $($app.DisplayName) $($app.DisplayVersion)"
        }
        $null = Uninstall-ADTApplication -InstalledApplication $installedApps
    }
    else
    {
        Write-ADTLogEntry -Message 'Product not found in the uninstall registry - nothing to remove.' -Severity 2
    }

    ##================================================
    ## MARK: Post-Uninstall
    ##================================================
    $adtSession.InstallPhase = "Post-$($adtSession.DeploymentType)"

    Write-ADTLogEntry -Message 'DLIllustr uninstallation completed.'
}


function Repair-ADTDeployment
{
    [CmdletBinding()]
    param ()

    ##================================================
    ## MARK: Pre-Repair
    ##================================================
    $adtSession.InstallPhase = "Pre-$($adtSession.DeploymentType)"

    if ($adtSession.AppProcessesToClose.Count -gt 0)
    {
        Show-ADTInstallationWelcome -CloseProcesses $adtSession.AppProcessesToClose -CloseProcessesCountdown 60
    }

    Show-ADTInstallationProgress -StatusMessage 'Repairing DLIllustr...'


    ##================================================
    ## MARK: Repair
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## Repair is implemented as a reinstall over the top, which is the supported
    ## approach for evergreen downloads where no MSI repair cache is guaranteed.
    Write-ADTLogEntry -Message 'Repair requested - reinstalling DLIllustr over the existing installation.'
    $installerPath = Get-AppInstaller

    ## Install the MSI. PSADT appends its own /qn and logging options.
    $null = Start-ADTMsiProcess -Action Install -FilePath $installerPath -AdditionalArgumentList @("ALLUSERS=1")

    ##================================================
    ## MARK: Post-Repair
    ##================================================
    $adtSession.InstallPhase = "Post-$($adtSession.DeploymentType)"

    Write-ADTLogEntry -Message 'DLIllustr repair completed.'
}


function Test-AppInstalled
{
    <#
    .SYNOPSIS
        Post-install verification using the same logic as the Intune detection script.
    .OUTPUTS
        System.Boolean
    #>
    [CmdletBinding()]
    [OutputType([System.Boolean])]
    param ()

    try
    {
        $found = Get-ADTApplication -Name '^DLIllustr v' -NameMatch Regex
        if ($found)
        {
            foreach ($app in $found)
            {
                Write-ADTLogEntry -Message "Detected: $($app.DisplayName) $($app.DisplayVersion)"
            }
            return $true
        }
        return $false
    }
    catch
    {
        Write-ADTLogEntry -Message "Verification check threw an error: $($_.Exception.Message)" -Severity 2
        return $false
    }
}


