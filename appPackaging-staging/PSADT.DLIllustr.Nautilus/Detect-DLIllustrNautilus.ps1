<#
.SYNOPSIS
    Intune detection script for Nautilus-DLIllustr.

.DESCRIPTION
    Returns 'installed' when Nautilus-DLIllustr is present, regardless of version. The matching
    PSADT package always deploys the current vendor release, so this script deliberately
    does not pin a version - it reports the installed version to Intune for reference.

    Detection method: RegistrySearch

.NOTES
    Version:        1.0.0
    Author:         Zachary Hayward with Kiro-claude-opus-5
    Creation Date:  2026-09-18
    Generated by:   new.psadt-package.ps1

    Returns:
    - Exit 0 + stdout: Nautilus-DLIllustr is installed
    - Exit 1:          Nautilus-DLIllustr is not installed
#>
$displayNamePattern = '^Nautilus-DLIllustr v'
## Minimum acceptable version. Nautilus-DLIllustr reuses one MSI ProductCode
## across versions ({95A90A7F-FA7D-4E04-B06F-6B6EE432744F}), so a ProductCode rule
## cannot tell builds apart and a stale older uninstall entry can linger. Gate on
## DisplayVersion so Intune only reports 'installed' for >= 3.8.0.
$minimumVersion = [version]'3.8.0'
$uninstallKeys = @(
    'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*'
    'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*'
    'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*'
)

try {
    ## NOTE: do not name this '$matches' - that collides with the automatic
    ## $Matches variable populated by the -match operator used below.
    $foundEntries = Get-ItemProperty -Path $uninstallKeys -ErrorAction SilentlyContinue |
        Where-Object { $_.DisplayName -match $displayNamePattern }

    foreach ($entry in $foundEntries) {
        ## Parse DisplayVersion defensively - fall back to the version embedded in
        ## the DisplayName (e.g. 'Nautilus-DLIllustr v3.8.0') when DisplayVersion is absent.
        $rawVersion = $entry.DisplayVersion
        if (-not $rawVersion -and $entry.DisplayName -match 'v(\d+(?:\.\d+){1,3})') {
            $rawVersion = $Matches[1]
        }

        $parsed = $null
        if ([version]::TryParse([string]$rawVersion, [ref]$parsed) -and $parsed -ge $minimumVersion) {
            Write-Output "Nautilus-DLIllustr is installed - Version: $rawVersion"
            exit 0
        }
    }
    exit 1
}
catch {
    exit 1
}

