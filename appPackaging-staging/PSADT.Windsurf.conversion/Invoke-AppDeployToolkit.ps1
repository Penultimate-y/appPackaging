##================================================
## MARK: Installer Acquisition
##================================================

function Get-AppInstaller
{
    <#
    .SYNOPSIS
        Returns a local path to the Windsurf Editor installer.
    .DESCRIPTION
        Prefers an installer staged in this package's Files folder. When none is present,
        resolves the current vendor download URL and downloads it to the PSADT temp folder.
    .OUTPUTS
        System.String. Full path to the installer on disk.
    #>
    [CmdletBinding()]
    [OutputType([System.String])]
    param ()

    ## Offline path: honour any installer staged in Files\ so the package works air-gapped.
    if ($adtSession.DirFiles -and (Test-Path -LiteralPath $adtSession.DirFiles))
    {
        $staged = Get-ChildItem -LiteralPath $adtSession.DirFiles -File -ErrorAction Ignore |
            Where-Object { $_.Extension -in '.msi', '.exe', '.zip' } |
            Select-Object -First 1

        if ($staged)
        {
            Write-ADTLogEntry -Message "Using installer staged in Files folder: $($staged.FullName)"
            return $staged.FullName
        }
    }

    ## Online path: resolve the current vendor download URL.
    $downloadUrl = $null
    $resolvedVersion = 'Unknown'

    try
    {
        ## Resolve the installer from the vendor's own update API.
        $apiUri = 'https://windsurf-stable.codeium.com/api/update/win32-x64-user/stable/latest'
        Write-ADTLogEntry -Message "Querying vendor update API: $apiUri"
        $response = Invoke-RestMethod -Uri $apiUri -UseBasicParsing -Headers @{ 'User-Agent' = 'DWX-PSADT-Deployment' }
        $downloadUrl = $response.'url'
        $resolvedVersion = $response.'productVersion'
        if (-not $downloadUrl)
        {
            throw "Vendor update API at $apiUri did not return a download URL property."
        }
    }
    catch
    {
        Write-ADTLogEntry -Message "Failed to resolve the Windsurf Editor download URL: $($_.Exception.Message)" -Severity 3
        throw
    }

    if ([System.String]::IsNullOrWhiteSpace($downloadUrl))
    {
        throw 'Resolved an empty download URL for Windsurf Editor.'
    }

    Write-ADTLogEntry -Message "Resolved Windsurf Editor version: $resolvedVersion"
    Write-ADTLogEntry -Message "Download URL: $downloadUrl"

    ## Download into the PSADT-managed temp folder so the session cleans it up.
    $destinationDir = if ($adtSession.DirSupportFiles) { $adtSession.DirSupportFiles } else { $env:TEMP }
    $installerPath = Join-Path -Path $destinationDir -ChildPath $script:InstallerFileName

    Show-ADTInstallationProgress -StatusMessage 'Downloading Windsurf Editor...'

    try
    {
        ## TLS 1.2 minimum - some vendor CDNs reject older suites.
        [System.Net.ServicePointManager]::SecurityProtocol = [System.Net.SecurityProtocolType]::Tls12
        Invoke-WebRequest -Uri $downloadUrl -OutFile $installerPath -UseBasicParsing
    }
    catch
    {
        Write-ADTLogEntry -Message "Download failed from $downloadUrl - $($_.Exception.Message)" -Severity 3
        throw
    }

    if (-not (Test-Path -LiteralPath $installerPath))
    {
        throw "Download reported success but no file exists at $installerPath."
    }

    $sizeMb = [System.Math]::Round((Get-Item -LiteralPath $installerPath).Length / 1MB, 2)
    if ($sizeMb -le 0)
    {
        throw "Downloaded installer at $installerPath is zero bytes."
    }

    Write-ADTLogEntry -Message "Download complete: $installerPath ($sizeMb MB)"
    return $installerPath
}


function Install-ADTDeployment
{
    [CmdletBinding()]
    param ()

    ##================================================
    ## MARK: Pre-Install
    ##================================================
    $adtSession.InstallPhase = "Pre-$($adtSession.DeploymentType)"

    ## Show welcome message and close the target application if it is running.
    $saiwParams = @{
        AllowDefer = $true
        DeferTimes = 3
        CheckDiskSpace = $true
        PersistPrompt = $true
    }
    if ($adtSession.AppProcessesToClose.Count -gt 0)
    {
        $saiwParams.Add('CloseProcesses', $adtSession.AppProcessesToClose)
    }
    Show-ADTInstallationWelcome @saiwParams

    Show-ADTInstallationProgress -StatusMessage 'Preparing Windsurf Editor installation...'


    ##================================================
    ## MARK: Install
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## Acquire the installer (staged file or fresh download).
    $installerPath = Get-AppInstaller

    Show-ADTInstallationProgress -StatusMessage 'Installing Windsurf Editor...'
    Write-ADTLogEntry -Message "Installing Windsurf Editor from: $installerPath"

    ## Run the vendor installer silently.
    $null = Start-ADTProcess -FilePath $installerPath -ArgumentList @("/VERYSILENT", "/NORESTART", "/MERGETASKS=!runcode") -WindowStyle Hidden

    ##================================================
    ## MARK: Post-Install
    ##================================================
    $adtSession.InstallPhase = "Post-$($adtSession.DeploymentType)"

    ## Verify the install landed where detection expects it.
    if (Test-AppInstalled)
    {
        Write-ADTLogEntry -Message 'Windsurf Editor installation verified successfully.'
    }
    else
    {
        Write-ADTLogEntry -Message 'Windsurf Editor installer completed but post-install verification failed.' -Severity 3
        throw 'Windsurf Editor post-install verification failed. Review the log and the vendor silent-install switches.'
    }

    if ($adtSession.DeployMode -ne 'Silent')
    {
        Show-ADTInstallationPrompt -Message 'Windsurf Editor has been installed successfully.' -ButtonRightText 'OK' -NoWait
    }
}


function Uninstall-ADTDeployment
{
    [CmdletBinding()]
    param ()

    ##================================================
    ## MARK: Pre-Uninstall
    ##================================================
    $adtSession.InstallPhase = "Pre-$($adtSession.DeploymentType)"

    if ($adtSession.AppProcessesToClose.Count -gt 0)
    {
        Show-ADTInstallationWelcome -CloseProcesses $adtSession.AppProcessesToClose -CloseProcessesCountdown 60
    }

    Show-ADTInstallationProgress -StatusMessage 'Removing Windsurf Editor...'


    ##================================================
    ## MARK: Uninstall
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## Locate the product in the uninstall registry and run its registered uninstall string.
    $installedApps = Get-ADTApplication -Name 'Windsurf|Devin' -NameMatch Regex
    if ($installedApps)
    {
        foreach ($app in $installedApps)
        {
            Write-ADTLogEntry -Message "Uninstalling: $($app.DisplayName) $($app.DisplayVersion)"
        }
        $null = Uninstall-ADTApplication -InstalledApplication $installedApps
    }
    else
    {
        Write-ADTLogEntry -Message 'Product not found in the uninstall registry - nothing to remove.' -Severity 2
    }

    ##================================================
    ## MARK: Post-Uninstall
    ##================================================
    $adtSession.InstallPhase = "Post-$($adtSession.DeploymentType)"

    Write-ADTLogEntry -Message 'Windsurf Editor uninstallation completed.'
}


function Repair-ADTDeployment
{
    [CmdletBinding()]
    param ()

    ##================================================
    ## MARK: Pre-Repair
    ##================================================
    $adtSession.InstallPhase = "Pre-$($adtSession.DeploymentType)"

    if ($adtSession.AppProcessesToClose.Count -gt 0)
    {
        Show-ADTInstallationWelcome -CloseProcesses $adtSession.AppProcessesToClose -CloseProcessesCountdown 60
    }

    Show-ADTInstallationProgress -StatusMessage 'Repairing Windsurf Editor...'


    ##================================================
    ## MARK: Repair
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## Repair is implemented as a reinstall over the top, which is the supported
    ## approach for evergreen downloads where no MSI repair cache is guaranteed.
    Write-ADTLogEntry -Message 'Repair requested - reinstalling Windsurf Editor over the existing installation.'
    $installerPath = Get-AppInstaller

    ## Run the vendor installer silently.
    $null = Start-ADTProcess -FilePath $installerPath -ArgumentList @("/VERYSILENT", "/NORESTART", "/MERGETASKS=!runcode") -WindowStyle Hidden

    ##================================================
    ## MARK: Post-Repair
    ##================================================
    $adtSession.InstallPhase = "Post-$($adtSession.DeploymentType)"

    Write-ADTLogEntry -Message 'Windsurf Editor repair completed.'
}


function Test-AppInstalled
{
    <#
    .SYNOPSIS
        Post-install verification using the same logic as the Intune detection script.
    .OUTPUTS
        System.Boolean
    #>
    [CmdletBinding()]
    [OutputType([System.Boolean])]
    param ()

    try
    {
        $found = Get-ADTApplication -Name 'Windsurf|Devin' -NameMatch Regex
        if ($found)
        {
            foreach ($app in $found)
            {
                Write-ADTLogEntry -Message "Detected: $($app.DisplayName) $($app.DisplayVersion)"
            }
            return $true
        }
        return $false
    }
    catch
    {
        Write-ADTLogEntry -Message "Verification check threw an error: $($_.Exception.Message)" -Severity 2
        return $false
    }
}


##================================================
## MARK: Initialization
##================================================

# Set strict error handling across entire operation.
$ErrorActionPreference = [System.Management.Automation.ActionPreference]::Stop
$ProgressPreference = [System.Management.Automation.ActionPreference]::SilentlyContinue
Set-StrictMode -Version 1

# Import the module and instantiate a new session.
try
{
    # Import the module locally if available, otherwise try to find it from PSModulePath.
    if (Test-Path -LiteralPath "$PSScriptRoot\PSAppDeployToolkit\PSAppDeployToolkit.psd1" -PathType Leaf)
    {
        Get-ChildItem -LiteralPath "$PSScriptRoot\PSAppDeployToolkit" -Recurse -File | Unblock-File -ErrorAction Ignore
        Import-Module -FullyQualifiedName @{ ModuleName = "$PSScriptRoot\PSAppDeployToolkit\PSAppDeployToolkit.psd1"; Guid = '8c3c366b-8606-4576-9f2d-4051144f7ca2'; ModuleVersion = '4.1.8' } -Force
    }
    else
    {
        Import-Module -FullyQualifiedName @{ ModuleName = 'PSAppDeployToolkit'; Guid = '8c3c366b-8606-4576-9f2d-4051144f7ca2'; ModuleVersion = '4.1.8' } -Force
    }

    # Open a new deployment session, replacing $adtSession with a DeploymentSession.
    $iadtParams = Get-ADTBoundParametersAndDefaultValues -Invocation $MyInvocation
    $adtSession = Remove-ADTHashtableNullOrEmptyValues -Hashtable $adtSession
    $adtSession = Open-ADTSession @adtSession @iadtParams -PassThru
}
catch
{
    $Host.UI.WriteErrorLine((Out-String -InputObject $_ -Width ([System.Int32]::MaxValue)))
    exit 60008
}


##================================================
## MARK: Invocation
##================================================

# Commence the actual deployment operation.
try
{
    # Import any found extensions before proceeding with the deployment.
    Get-ChildItem -LiteralPath $PSScriptRoot -Directory | & {
        process
        {
            if ($_.Name -match 'PSAppDeployToolkit\..+$')
            {
                Get-ChildItem -LiteralPath $_.FullName -Recurse -File | Unblock-File -ErrorAction Ignore
                Import-Module -Name $_.FullName -Force
            }
        }
    }

    # Invoke the deployment and close out the session.
    & "$($adtSession.DeploymentType)-ADTDeployment"
    Close-ADTSession
}
catch
{
    # An unhandled error has been caught.
    $mainErrorMessage = "An unhandled error within [$($MyInvocation.MyCommand.Name)] has occurred.`n$(Resolve-ADTErrorRecord -ErrorRecord $_)"
    Write-ADTLogEntry -Message $mainErrorMessage -Severity 3
    Close-ADTSession -ExitCode 60001
}
