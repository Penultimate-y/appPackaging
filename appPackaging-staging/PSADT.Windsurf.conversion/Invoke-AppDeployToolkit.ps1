<#

.SYNOPSIS
PSAppDeployToolkit - Installs or uninstalls Windsurf Editor.

.DESCRIPTION
Downloads the current Windsurf Editor installer from the vendor at run time and installs it
silently, then verifies the result. No installation media is embedded in this package, so
the .intunewin stays small and the deployment does not need to be rebuilt for each release.

If an installer is staged in this package's Files folder it is used instead of downloading,
which allows the same package to be used on isolated networks.

Generated by new.psadt-package.ps1 from psadt-app-catalog.json.
Template source: PSADT.Kiro.IDE
Legacy predecessor(s): legacy.Windsurf, legacy.Codeium, legacy.Kiro_Windsurf
Supersedes Intune app(s): none recorded

.PARAMETER DeploymentType
The type of deployment to perform.

.PARAMETER DeployMode
Specifies whether the installation should be run in Interactive, Silent, NonInteractive or Auto mode.

.PARAMETER SuppressRebootPassThru
Suppresses the 3010 return code (requires restart) from being passed back to the parent process.

.PARAMETER TerminalServerMode
Changes to "user install mode" and back to "user execute mode" for RDSH/Citrix servers.

.PARAMETER DisableLogging
Disables logging to file for the script.

.EXAMPLE
Invoke-AppDeployToolkit.exe -DeploymentType Install -DeployMode Silent

.EXAMPLE
Invoke-AppDeployToolkit.exe -DeploymentType Uninstall -DeployMode Silent

.NOTES
TEST GROUP REQUIREMENT
    App assignment changes affect every targeted device and user. Assign this package to
    the DWX application pilot group and confirm a successful install, detection and
    uninstall on at least one device per supported build before widening the assignment.

PACKAGING NOTES
    Resolved from the vendor's own stable update API (the windsurf.com download page returns HTTP 403 to scripted clients).
    NOTE: the vendor is rebranding Windsurf to Devin - the API currently returns a DevinUserSetup-x64 installer, so detection and uninstall match on either name.
    Confirm the installed display name in your pilot group.

Toolkit Exit Code Ranges:
- 60000 - 68999: Reserved for built-in exit codes in Invoke-AppDeployToolkit.ps1/.exe
- 69000 - 69999: Recommended for user customized exit codes in Invoke-AppDeployToolkit.ps1
- 70000 - 79999: Recommended for user customized exit codes in PSAppDeployToolkit.Extensions module.

.LINK
https://psappdeploytoolkit.com

#>

