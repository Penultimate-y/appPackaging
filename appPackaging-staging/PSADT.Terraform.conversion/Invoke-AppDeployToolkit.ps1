##================================================
## MARK: Installer Acquisition
##================================================

function Get-AppInstaller
{
    <#
    .SYNOPSIS
        Returns a local path to the Terraform installer.
    .DESCRIPTION
        Prefers an installer staged in this package's Files folder. When none is present,
        resolves the current vendor download URL and downloads it to the PSADT temp folder.
    .OUTPUTS
        System.String. Full path to the installer on disk.
    #>
    [CmdletBinding()]
    [OutputType([System.String])]
    param ()

    ## Offline path: honour any installer staged in Files\ so the package works air-gapped.
    if ($adtSession.DirFiles -and (Test-Path -LiteralPath $adtSession.DirFiles))
    {
        $staged = Get-ChildItem -LiteralPath $adtSession.DirFiles -File -ErrorAction Ignore |
            Where-Object { $_.Extension -in '.msi', '.exe', '.zip' } |
            Select-Object -First 1

        if ($staged)
        {
            Write-ADTLogEntry -Message "Using installer staged in Files folder: $($staged.FullName)"
            return $staged.FullName
        }
    }

    ## Online path: resolve the current vendor download URL.
    $downloadUrl = $null
    $resolvedVersion = 'Unknown'

    try
    {
        ## Resolve the latest release build from the HashiCorp releases API.
        $apiUri = 'https://api.releases.hashicorp.com/v1/releases/terraform/latest'
        Write-ADTLogEntry -Message "Querying HashiCorp releases: $apiUri"
        $release = Invoke-RestMethod -Uri $apiUri -UseBasicParsing
        $build = $release.builds | Where-Object { $_.url -match '_windows_amd64\.zip$' } | Select-Object -First 1
        if (-not $build)
        {
            throw "No HashiCorp build matched the expected pattern in terraform $($release.version)."
        }
        $downloadUrl = $build.url
        $resolvedVersion = $release.version
    }
    catch
    {
        Write-ADTLogEntry -Message "Failed to resolve the Terraform download URL: $($_.Exception.Message)" -Severity 3
        throw
    }

    if ([System.String]::IsNullOrWhiteSpace($downloadUrl))
    {
        throw 'Resolved an empty download URL for Terraform.'
    }

    Write-ADTLogEntry -Message "Resolved Terraform version: $resolvedVersion"
    Write-ADTLogEntry -Message "Download URL: $downloadUrl"

    ## Download into the PSADT-managed temp folder so the session cleans it up.
    $destinationDir = if ($adtSession.DirSupportFiles) { $adtSession.DirSupportFiles } else { $env:TEMP }
    $installerPath = Join-Path -Path $destinationDir -ChildPath $script:InstallerFileName

    Show-ADTInstallationProgress -StatusMessage 'Downloading Terraform...'

    try
    {
        ## TLS 1.2 minimum - some vendor CDNs reject older suites.
        [System.Net.ServicePointManager]::SecurityProtocol = [System.Net.SecurityProtocolType]::Tls12
        Invoke-WebRequest -Uri $downloadUrl -OutFile $installerPath -UseBasicParsing
    }
    catch
    {
        Write-ADTLogEntry -Message "Download failed from $downloadUrl - $($_.Exception.Message)" -Severity 3
        throw
    }

    if (-not (Test-Path -LiteralPath $installerPath))
    {
        throw "Download reported success but no file exists at $installerPath."
    }

    $sizeMb = [System.Math]::Round((Get-Item -LiteralPath $installerPath).Length / 1MB, 2)
    if ($sizeMb -le 0)
    {
        throw "Downloaded installer at $installerPath is zero bytes."
    }

    Write-ADTLogEntry -Message "Download complete: $installerPath ($sizeMb MB)"
    return $installerPath
}


function Install-ADTDeployment
{
    [CmdletBinding()]
    param ()

    ##================================================
    ## MARK: Pre-Install
    ##================================================
    $adtSession.InstallPhase = "Pre-$($adtSession.DeploymentType)"

    ## Show welcome message and close the target application if it is running.
    $saiwParams = @{
        AllowDefer = $true
        DeferTimes = 3
        CheckDiskSpace = $true
        PersistPrompt = $true
    }
    if ($adtSession.AppProcessesToClose.Count -gt 0)
    {
        $saiwParams.Add('CloseProcesses', $adtSession.AppProcessesToClose)
    }
    Show-ADTInstallationWelcome @saiwParams

    Show-ADTInstallationProgress -StatusMessage 'Preparing Terraform installation...'


    ##================================================
    ## MARK: Install
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## Acquire the installer (staged file or fresh download).
    $installerPath = Get-AppInstaller

    Show-ADTInstallationProgress -StatusMessage 'Installing Terraform...'
    Write-ADTLogEntry -Message "Installing Terraform from: $installerPath"

    ## Archive deployment: replace the target directory with the archive contents.
    $installDir = "$env:ProgramFiles\Terraform"
    Write-ADTLogEntry -Message "Extracting archive to: $installDir"
    if (Test-Path -LiteralPath $installDir)
    {
        Remove-ADTFolder -Path $installDir
    }
    $null = New-Item -Path $installDir -ItemType Directory -Force
    Expand-Archive -LiteralPath $installerPath -DestinationPath $installDir -Force

    ## Add the install directory to the machine PATH if it is not already present.
    $machinePath = [System.Environment]::GetEnvironmentVariable('Path', 'Machine')
    if ($machinePath -notlike "*$installDir*")
    {
        Write-ADTLogEntry -Message "Adding $installDir to the machine PATH"
        [System.Environment]::SetEnvironmentVariable('Path', ($machinePath.TrimEnd(';') + ';' + $installDir), 'Machine')
    }
    else
    {
        Write-ADTLogEntry -Message "Machine PATH already contains $installDir"
    }

    ##================================================
    ## MARK: Post-Install
    ##================================================
    $adtSession.InstallPhase = "Post-$($adtSession.DeploymentType)"

    ## Verify the install landed where detection expects it.
    if (Test-AppInstalled)
    {
        Write-ADTLogEntry -Message 'Terraform installation verified successfully.'
    }
    else
    {
        Write-ADTLogEntry -Message 'Terraform installer completed but post-install verification failed.' -Severity 3
        throw 'Terraform post-install verification failed. Review the log and the vendor silent-install switches.'
    }

    if ($adtSession.DeployMode -ne 'Silent')
    {
        Show-ADTInstallationPrompt -Message 'Terraform has been installed successfully.' -ButtonRightText 'OK' -NoWait
    }
}


function Uninstall-ADTDeployment
{
    [CmdletBinding()]
    param ()

    ##================================================
    ## MARK: Pre-Uninstall
    ##================================================
    $adtSession.InstallPhase = "Pre-$($adtSession.DeploymentType)"

    if ($adtSession.AppProcessesToClose.Count -gt 0)
    {
        Show-ADTInstallationWelcome -CloseProcesses $adtSession.AppProcessesToClose -CloseProcessesCountdown 60
    }

    Show-ADTInstallationProgress -StatusMessage 'Removing Terraform...'


    ##================================================
    ## MARK: Uninstall
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## Archive deployment: remove the install directory.
    $targetDir = "$env:ProgramFiles\Terraform"
    if (Test-Path -LiteralPath $targetDir)
    {
        Write-ADTLogEntry -Message "Removing directory: $targetDir"
        Remove-ADTFolder -Path $targetDir
    }
    else
    {
        Write-ADTLogEntry -Message "Directory not found: $targetDir" -Severity 2
    }

    ## Remove the install directory from the machine PATH.
    $machinePath = [System.Environment]::GetEnvironmentVariable('Path', 'Machine')
    $newPath = (($machinePath -split ';') | Where-Object { $_ -and ($_.TrimEnd('\') -ne $targetDir.TrimEnd('\')) }) -join ';'
    if ($newPath -ne $machinePath)
    {
        Write-ADTLogEntry -Message "Removing $targetDir from the machine PATH"
        [System.Environment]::SetEnvironmentVariable('Path', $newPath, 'Machine')
    }

    ##================================================
    ## MARK: Post-Uninstall
    ##================================================
    $adtSession.InstallPhase = "Post-$($adtSession.DeploymentType)"

    Write-ADTLogEntry -Message 'Terraform uninstallation completed.'
}


