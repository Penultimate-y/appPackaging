function Test-AppInstalled
{
    <#
    .SYNOPSIS
        Post-install verification using the same logic as the Intune detection script.
    .OUTPUTS
        System.Boolean
    #>
    [CmdletBinding()]
    [OutputType([System.Boolean])]
    param ()

    try
    {
        $targetPath = "$env:ProgramFiles\Terraform\terraform.exe"
        if (Test-Path -LiteralPath $targetPath)
        {
            $fileVersion = (Get-Item -LiteralPath $targetPath).VersionInfo.FileVersion
            Write-ADTLogEntry -Message "Detected Terraform at $targetPath (version $fileVersion)"
            return $true
        }
        return $false
    }
    catch
    {
        Write-ADTLogEntry -Message "Verification check threw an error: $($_.Exception.Message)" -Severity 2
        return $false
    }
}


