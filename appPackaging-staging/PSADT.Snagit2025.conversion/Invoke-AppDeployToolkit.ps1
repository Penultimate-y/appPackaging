    Show-ADTInstallationProgress -StatusMessage 'Repairing Snagit 2025...'


    ##================================================
    ## MARK: Repair
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## Repair is implemented as a reinstall over the top, which is the supported
    ## approach for evergreen downloads where no MSI repair cache is guaranteed.
    Write-ADTLogEntry -Message 'Repair requested - reinstalling Snagit 2025 over the existing installation.'
    $installerPath = Get-AppInstaller

    ## Resolve the volume-licence MST transform (prompts on an interactive run,
    ## auto-selects the single staged .mst under Intune/Silent context).
