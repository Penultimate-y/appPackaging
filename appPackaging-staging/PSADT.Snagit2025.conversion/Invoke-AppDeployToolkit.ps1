function Get-AppInstaller
{
    <#
    .SYNOPSIS
        Returns a local path to the Snagit 2025 installer.
    .DESCRIPTION
        Prefers an installer staged in this package's Files folder. When none is present,
        resolves the current vendor download URL and downloads it to the PSADT temp folder.
    .OUTPUTS
        System.String. Full path to the installer on disk.
    #>
    [CmdletBinding()]
    [OutputType([System.String])]
    param ()

    ## Offline path: honour any installer staged in Files\ so the package works air-gapped.
    if ($adtSession.DirFiles -and (Test-Path -LiteralPath $adtSession.DirFiles))
    {
        $staged = Get-ChildItem -LiteralPath $adtSession.DirFiles -File -ErrorAction Ignore |
            Where-Object { $_.Extension -in '.msi', '.exe', '.zip' } |
            Select-Object -First 1

        if ($staged)
        {
            Write-ADTLogEntry -Message "Using installer staged in Files folder: $($staged.FullName)"
            return $staged.FullName
        }
    }

    ## Online path: resolve the current vendor download URL.
    $downloadUrl = $null
    $resolvedVersion = 'Unknown'

    try
    {
        ## This vendor blocks automated downloads, so there is no resolvable URL.
        ## The installer MUST be staged in the package Files folder (checked above).
        $guidance = @(
            'No installer was found in the package Files folder.'
            ''
            'Snagit 2025 has no automation-friendly public download URL - the vendor blocks'
            'scripted downloads, so this package cannot fetch the installer itself.'
            ''
            'To use this package:'
            '  1. Download Snagit 2025 manually from: https://www.techsmith.com/download/snagit/ (use the TechSmith Deployment Tool to generate the volume-licensed snagit.msi + snagit.mst transform, then stage BOTH in the package Files folder)'
            '  2. Place the installer in the package Files folder (any .msi, .exe or .zip).'
            '  3. Rebuild the .intunewin and re-upload it to Intune.'
        ) -join [System.Environment]::NewLine
        throw $guidance
    }
    catch
    {
        Write-ADTLogEntry -Message "Failed to resolve the Snagit 2025 download URL: $($_.Exception.Message)" -Severity 3
        throw
    }

    if ([System.String]::IsNullOrWhiteSpace($downloadUrl))
    {
        throw 'Resolved an empty download URL for Snagit 2025.'
    }

    Write-ADTLogEntry -Message "Resolved Snagit 2025 version: $resolvedVersion"
    Write-ADTLogEntry -Message "Download URL: $downloadUrl"

    ## Download into the PSADT-managed temp folder so the session cleans it up.
    $destinationDir = if ($adtSession.DirSupportFiles) { $adtSession.DirSupportFiles } else { $env:TEMP }
    $installerPath = Join-Path -Path $destinationDir -ChildPath $script:InstallerFileName

    Show-ADTInstallationProgress -StatusMessage 'Downloading Snagit 2025...'

    try
    {
        ## TLS 1.2 minimum - some vendor CDNs reject older suites.
        [System.Net.ServicePointManager]::SecurityProtocol = [System.Net.SecurityProtocolType]::Tls12
        Invoke-WebRequest -Uri $downloadUrl -OutFile $installerPath -UseBasicParsing
    }
    catch
    {
        Write-ADTLogEntry -Message "Download failed from $downloadUrl - $($_.Exception.Message)" -Severity 3
        throw
    }

    if (-not (Test-Path -LiteralPath $installerPath))
    {
        throw "Download reported success but no file exists at $installerPath."
    }

    $sizeMb = [System.Math]::Round((Get-Item -LiteralPath $installerPath).Length / 1MB, 2)
    if ($sizeMb -le 0)
    {
        throw "Downloaded installer at $installerPath is zero bytes."
    }

    Write-ADTLogEntry -Message "Download complete: $installerPath ($sizeMb MB)"
    return $installerPath
}


function Resolve-AppTransform
{
    <#
    .SYNOPSIS
        Returns the MST transform(s) to apply to the Snagit 2025 MSI, or $null for none.
    .DESCRIPTION
        Snagit 2025 is deployed with a TechSmith volume-licence MST transform (the transform
        carries the licence key and configuration so users are not prompted to activate), as
        the legacy.SnagIt scripts did via "TRANSFORMS=snagit.mst".

        Behaviour by run context:
          * Interactive (build / pilot / manual run): PROMPTS the operator for the transform-
            file questions - whether to apply a transform, and which staged .mst to use. This
            is the operator-facing "transform file questions during build" behaviour.
          * Silent / NonInteractive (Intune SYSTEM context): never prompts. Auto-applies the
            single staged .mst when exactly one is present; logs and installs without a
            transform otherwise, so unattended deployment never stalls.

        Transforms are matched from any .mst files staged in the package Files folder.
    .OUTPUTS
        System.String. A semicolon-separated absolute path list of .mst files, or $null.
    #>
    [CmdletBinding()]
    [OutputType([System.String])]
    param ()

    ## Enumerate any .mst transforms staged alongside the MSI in Files\.
    $transforms = @()
    if ($adtSession.DirFiles -and (Test-Path -LiteralPath $adtSession.DirFiles))
    {
        $transforms = @(Get-ChildItem -LiteralPath $adtSession.DirFiles -Filter '*.mst' -File -ErrorAction Ignore |
            Sort-Object -Property Name)
    }

    ## Decide whether this run may prompt. Only a truly interactive operator run should.
    $isInteractive = ($adtSession.DeployMode -eq 'Interactive') -and
        ([System.Environment]::UserInteractive) -and
        (-not [System.Console]::IsInputRedirected)

    if (-not $isInteractive)
    {
        ## Unattended (Intune/SYSTEM/Silent): never prompt.
        if ($transforms.Count -eq 1)
        {
            Write-ADTLogEntry -Message "Silent context - auto-applying staged transform: $($transforms[0].Name)"
            return $transforms[0].FullName
        }
        if ($transforms.Count -gt 1)
        {
            ## Ambiguous and we cannot ask - apply all staged transforms in name order,
            ## which is msiexec's documented left-to-right precedence.
            $all = ($transforms | ForEach-Object { $_.FullName }) -join ';'
            Write-ADTLogEntry -Message "Silent context - multiple transforms staged; applying all in order: $(( $transforms | ForEach-Object { $_.Name }) -join ', ')" -Severity 2
            return $all
        }
        Write-ADTLogEntry -Message 'Silent context - no .mst transform staged; installing without a transform.' -Severity 2
        return $null
    }

    ## Interactive build/pilot run: ask the operator the transform-file questions.
    Write-ADTLogEntry -Message 'Interactive context - prompting operator for transform-file selection.'

    if ($transforms.Count -eq 0)
    {
        Write-Output ''
        Write-Output 'No .mst transform files were found in the package Files folder.'
        $staged = Read-Host "Apply a Snagit 2025 MST transform anyway? Enter a full path to an .mst, or press Enter to install WITHOUT a transform"
        if ([System.String]::IsNullOrWhiteSpace($staged))
        {
            Write-ADTLogEntry -Message 'Operator chose to install without a transform.'
            return $null
        }
        if (-not (Test-Path -LiteralPath $staged -PathType Leaf))
        {
            throw "Operator supplied a transform path that does not exist: $staged"
        }
        Write-ADTLogEntry -Message "Operator supplied transform: $staged"
        return (Resolve-Path -LiteralPath $staged).Path
    }

    ## One or more transforms are staged - present the choices.
    Write-Output ''
    Write-Output 'Snagit 2025 - MST transform selection'
    Write-Output '-------------------------------------'
    Write-Output 'The following transform file(s) are staged in the package Files folder:'
    for ($i = 0; $i -lt $transforms.Count; $i++)
    {
        Write-Output ("  [{0}] {1}" -f ($i + 1), $transforms[$i].Name)
    }
    Write-Output '  [A] Apply ALL of the above, in the order listed'
    Write-Output '  [N] Install with NO transform'
    Write-Output ''

    while ($true)
    {
        $choice = (Read-Host "Select a transform to apply (1-$($transforms.Count), A, or N)").Trim()

        if ($choice -match '^[Nn]$')
        {
            Write-ADTLogEntry -Message 'Operator chose to install without a transform.'
            return $null
        }
        if ($choice -match '^[Aa]$')
        {
            $all = ($transforms | ForEach-Object { $_.FullName }) -join ';'
            Write-ADTLogEntry -Message "Operator chose to apply all transforms: $(( $transforms | ForEach-Object { $_.Name }) -join ', ')"
            return $all
        }

        $index = 0
        if ([int]::TryParse($choice, [ref]$index) -and $index -ge 1 -and $index -le $transforms.Count)
        {
            $selected = $transforms[$index - 1]
            Write-ADTLogEntry -Message "Operator selected transform: $($selected.Name)"
            return $selected.FullName
        }

        Write-Output "Invalid selection '$choice'. Enter a number between 1 and $($transforms.Count), A, or N."
    }
}


function Install-ADTDeployment
{
    [CmdletBinding()]
    param ()

    ##================================================
    ## MARK: Pre-Install
    ##================================================
    $adtSession.InstallPhase = "Pre-$($adtSession.DeploymentType)"

    ## Show welcome message and close the target application if it is running.
    $saiwParams = @{
        AllowDefer = $true
        DeferTimes = 3
        CheckDiskSpace = $true
        PersistPrompt = $true
    }
    if ($adtSession.AppProcessesToClose.Count -gt 0)
    {
        $saiwParams.Add('CloseProcesses', $adtSession.AppProcessesToClose)
    }
    Show-ADTInstallationWelcome @saiwParams

    Show-ADTInstallationProgress -StatusMessage 'Preparing Snagit 2025 installation...'


    ##================================================
    ## MARK: Install
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## Acquire the installer (staged file or fresh download).
    $installerPath = Get-AppInstaller

    Show-ADTInstallationProgress -StatusMessage 'Installing Snagit 2025...'
    Write-ADTLogEntry -Message "Installing Snagit 2025 from: $installerPath"

    ## Resolve the volume-licence MST transform (prompts the operator on an interactive run,
    ## auto-selects the single staged .mst under Intune/Silent context).
    $transformPath = Resolve-AppTransform

    ## Build the MSI argument list, adding TRANSFORMS= when a transform was chosen.
    $msiArgs = @("ALLUSERS=1", "TSC_SUPPRESS_REBOOT=1", "DESKTOP_SHORTCUT=0")
    if (-not [System.String]::IsNullOrWhiteSpace($transformPath))
    {
        Write-ADTLogEntry -Message "Applying MST transform(s): $transformPath"
        $msiArgs += "TRANSFORMS=`"$transformPath`""
    }

    ## Install the MSI. PSADT appends its own /qn and logging options.
    $null = Start-ADTMsiProcess -Action Install -FilePath $installerPath -AdditionalArgumentList $msiArgs

    ##================================================
    ## MARK: Post-Install
    ##================================================
    $adtSession.InstallPhase = "Post-$($adtSession.DeploymentType)"

    ## Verify the install landed where detection expects it.
    if (Test-AppInstalled)
    {
        Write-ADTLogEntry -Message 'Snagit 2025 installation verified successfully.'
    }
    else
    {
        Write-ADTLogEntry -Message 'Snagit 2025 installer completed but post-install verification failed.' -Severity 3
        throw 'Snagit 2025 post-install verification failed. Review the log and the vendor silent-install switches.'
    }

    if ($adtSession.DeployMode -ne 'Silent')
    {
        Show-ADTInstallationPrompt -Message 'Snagit 2025 has been installed successfully.' -ButtonRightText 'OK' -NoWait
    }
}


function Uninstall-ADTDeployment
{
    [CmdletBinding()]
    param ()

    ##================================================
    ## MARK: Pre-Uninstall
    ##================================================
    $adtSession.InstallPhase = "Pre-$($adtSession.DeploymentType)"

    if ($adtSession.AppProcessesToClose.Count -gt 0)
    {
        Show-ADTInstallationWelcome -CloseProcesses $adtSession.AppProcessesToClose -CloseProcessesCountdown 60
    }

    Show-ADTInstallationProgress -StatusMessage 'Removing Snagit 2025...'


    ##================================================
    ## MARK: Uninstall
    ##================================================
    $adtSession.InstallPhase = $adtSession.DeploymentType

    ## Locate the product in the uninstall registry and run its registered uninstall string.
    $installedApps = Get-ADTApplication -Name '^Snagit 2025|^Snagit 25\.' -NameMatch Regex
    if ($installedApps)
    {
        foreach ($app in $installedApps)
        {
            Write-ADTLogEntry -Message "Uninstalling: $($app.DisplayName) $($app.DisplayVersion)"
        }
        $null = Uninstall-ADTApplication -InstalledApplication $installedApps
    }
    else
    {
        Write-ADTLogEntry -Message 'Product not found in the uninstall registry - nothing to remove.' -Severity 2
    }

    ##================================================
    ## MARK: Post-Uninstall
    ##================================================
    $adtSession.InstallPhase = "Post-$($adtSession.DeploymentType)"

    Write-ADTLogEntry -Message 'Snagit 2025 uninstallation completed.'
}


function Repair-ADTDeployment
{
