<#
.SYNOPSIS
    Intune detection script for Microsoft Teams.

.DESCRIPTION
    Returns 'installed' when Microsoft Teams is present, regardless of version. The matching
    PSADT package always deploys the current vendor release, so this script deliberately
    does not pin a version - it reports the installed version to Intune for reference.

    Detection method: Appx

.NOTES
    Version:        1.0.0
    Author:         Zachary Hayward with Kiro-claude-opus-5
    Creation Date:  2026-09-18
    Generated by:   new.psadt-package.ps1

    Returns:
    - Exit 0 + stdout: Microsoft Teams is installed
    - Exit 1:          Microsoft Teams is not installed
#>
$packageName = 'MSTeams'

try {
    $pkg = Get-AppxPackage -AllUsers -Name $packageName -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($pkg) {
        Write-Output "Microsoft Teams is installed - Version: $($pkg.Version)"
        exit 0
    }
    exit 1
}
catch {
    exit 1
}

