<#
.SYNOPSIS
    Intune detection script for Visual Studio Code.

.DESCRIPTION
    Returns 'installed' when Visual Studio Code is present, regardless of version. The matching
    PSADT package always deploys the current vendor release, so this script deliberately
    does not pin a version - it reports the installed version to Intune for reference.

    Detection method: File

.NOTES
    Version:        1.0.0
    Author:         Zachary Hayward with Kiro-claude-opus-5
    Creation Date:  2026-09-18
    Generated by:   new.psadt-package.ps1

    Returns:
    - Exit 0 + stdout: Visual Studio Code is installed
    - Exit 1:          Visual Studio Code is not installed
#>
$targetPath = "$env:ProgramFiles\Microsoft VS Code\Code.exe"

try {
    if (Test-Path -LiteralPath $targetPath) {
        $fileVersion = (Get-Item -LiteralPath $targetPath).VersionInfo.FileVersion
        Write-Output "Visual Studio Code is installed - Version: $fileVersion"
        exit 0
    }
    exit 1
}
catch {
    exit 1
}

