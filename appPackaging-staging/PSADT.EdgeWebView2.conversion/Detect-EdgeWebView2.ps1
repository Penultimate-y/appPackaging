<#
.SYNOPSIS
    Intune detection script for Edge WebView2 Runtime.

.DESCRIPTION
    Returns 'installed' when Edge WebView2 Runtime is present, regardless of version. The matching
    PSADT package always deploys the current vendor release, so this script deliberately
    does not pin a version - it reports the installed version to Intune for reference.

    Detection method: RegistrySearch

.NOTES
    Version:        1.0.0
    Author:         Zachary Hayward with Kiro-claude-opus-5
    Creation Date:  2026-09-18
    Generated by:   new.psadt-package.ps1

    Returns:
    - Exit 0 + stdout: Edge WebView2 Runtime is installed
    - Exit 1:          Edge WebView2 Runtime is not installed
#>
$displayNamePattern = 'Microsoft Edge WebView2 Runtime'
$uninstallKeys = @(
    'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*'
    'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*'
    'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*'
)

try {
    $match = Get-ItemProperty -Path $uninstallKeys -ErrorAction SilentlyContinue |
        Where-Object { $_.DisplayName -match $displayNamePattern } |
        Select-Object -First 1

    if ($match) {
        Write-Output "Edge WebView2 Runtime is installed - Version: $($match.DisplayVersion)"
        exit 0
    }
    exit 1
}
catch {
    exit 1
}

