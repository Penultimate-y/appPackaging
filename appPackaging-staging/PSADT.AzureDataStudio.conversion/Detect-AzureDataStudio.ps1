<#
.SYNOPSIS
    Intune detection script for Azure Data Studio.

.DESCRIPTION
    Returns 'installed' when Azure Data Studio is present, regardless of version. The matching
    PSADT package always deploys the current vendor release, so this script deliberately
    does not pin a version - it reports the installed version to Intune for reference.

    Detection method: File

.NOTES
    Version:        1.0.0
    Author:         Zachary Hayward with Kiro-claude-opus-5
    Creation Date:  2026-09-18
    Generated by:   new.psadt-package.ps1

    Returns:
    - Exit 0 + stdout: Azure Data Studio is installed
    - Exit 1:          Azure Data Studio is not installed
#>
$targetPath = "$env:ProgramFiles\Azure Data Studio\azuredatastudio.exe"

try {
    if (Test-Path -LiteralPath $targetPath) {
        $fileVersion = (Get-Item -LiteralPath $targetPath).VersionInfo.FileVersion
        Write-Output "Azure Data Studio is installed - Version: $fileVersion"
        exit 0
    }
    exit 1
}
catch {
    exit 1
}

