# ----- Load config file if provided -----
$loadedConfig = @{}
$inputSource = 'Interactive'
if (-not [string]::IsNullOrWhiteSpace($ConfigFile)) {
    try {
        $loadedConfig = Import-DeploymentConfig -Path $ConfigFile
        $inputSource  = 'ConfigFile'
        Write-Host "Loaded config from: $ConfigFile" -ForegroundColor Green
    }
    catch {
        Write-Host "ERROR loading config: $_" -ForegroundColor Red
        return
    }
}

# ----- Collect (or load) user input -----
$userInput = Get-UserInput -Config $loadedConfig -NoConfirm:$NoConfirm

if ($null -eq $userInput) {
    Write-Host ""
    Write-Host "Operation cancelled by user. No deployment was executed." -ForegroundColor Yellow
    return
}

# ----- Optional: save current run's inputs as a reusable config -----
if (-not [string]::IsNullOrWhiteSpace($SaveConfig)) {
    try {
        Save-DeploymentConfig -UserInput $userInput -Path $SaveConfig
    }
    catch {
        Write-Host "WARNING: Failed to save config to '$SaveConfig': $_" -ForegroundColor Yellow
    }
}

Write-Host ""
Write-Host "Confirmed. Generating standalone deployment script..." -ForegroundColor Green

# ----- Generate the standalone script -----
$templatePath    = Join-Path $PSScriptRoot 'Application_Script_Template_Automate.ps1'
$outputDirectory = Join-Path $PSScriptRoot 'Generated'

try {
    $generatedScript = New-StandaloneDeploymentScript `
        -TemplatePath    $templatePath `
        -OutputDirectory $outputDirectory `
        -UserInput       $userInput

    Write-Host "Standalone script saved to:" -ForegroundColor Green
    Write-Host "  $generatedScript" -ForegroundColor Green
    Write-Host ""
}
catch {
    Write-Host "Failed to generate standalone script: $_" -ForegroundColor Red
    Write-Host "Aborting deployment." -ForegroundColor Red
    return
}

# ----- Build & write the manifest -----
$manifest = New-DeploymentManifest `
    -UserInput           $userInput `
    -GeneratedScriptPath $generatedScript `
    -ConfigFilePath      $ConfigFile `
    -InputSource         $inputSource

$manifestPath = Write-DeploymentManifest `
    -Manifest            $manifest `
    -GeneratedScriptPath $generatedScript `
    -OutputDirectory     $outputDirectory

$rollingLogPath = Join-Path $outputDirectory 'manifest_log.jsonl'

# ----- Run-now decision -----
if ($NoConfirm) {
    $runNow = 'Y'
    Write-Host "[-NoConfirm] Running generated script automatically." -ForegroundColor DarkCyan
}
else {
    do {
        $runNow = Read-Host "Run the generated script now? (Y/N)"
    } while ($runNow -notmatch '^(Y|y|Yes|yes|N|n|No|no)$')
}

if ($runNow -match '^(Y|y|Yes|yes)$') {
    Write-Host "Executing generated script..." -ForegroundColor Green
    $execStart = Get-Date
    $exitCode  = 0
    try {
        & $generatedScript
        $exitCode = $LASTEXITCODE
        if ($null -eq $exitCode) { $exitCode = 0 }
    }
    catch {
        Write-Host "Generated script threw an exception: $_" -ForegroundColor Red
        $exitCode = -1
    }
    $execEnd  = Get-Date
    $duration = ($execEnd - $execStart).TotalSeconds

    Update-ManifestExecution `
        -ManifestPath     $manifestPath `
        -RollingLogPath   $rollingLogPath `
        -Executed         $true `
        -ExitCode         $exitCode `
        -DurationSeconds  $duration

    Write-Host ""
    Write-Host "Execution complete. Exit code: $exitCode (took $([math]::Round($duration,1))s)" -ForegroundColor Cyan
}
else {
    Update-ManifestExecution `
        -ManifestPath     $manifestPath `
        -RollingLogPath   $rollingLogPath `
        -Executed         $false

    Write-Host "Generated script saved but not executed. You can run it later from:" -ForegroundColor Yellow
    Write-Host "  $generatedScript" -ForegroundColor Yellow
}

