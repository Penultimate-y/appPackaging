function Write-DeploymentManifest {
    <#
        Write the manifest to two places:
          1. A per-generation .json file alongside the .ps1
          2. Append a single-line record to manifest_log.jsonl in the Generated/ folder
    #>
    param(
        [Parameter(Mandatory)] [PSCustomObject]$Manifest,
        [Parameter(Mandatory)] [string]$GeneratedScriptPath,
        [Parameter(Mandatory)] [string]$OutputDirectory
    )

    # Per-generation file (same base name as the .ps1 but with .json)
    $perGenPath = [System.IO.Path]::ChangeExtension($GeneratedScriptPath, '.json')
    $Manifest | ConvertTo-Json -Depth 8 | Out-File -FilePath $perGenPath -Encoding UTF8 -Force
    Write-Host "Per-deployment manifest: $perGenPath" -ForegroundColor Cyan

    # Rolling JSONL log (one record per line, append-only)
    $rollingPath = Join-Path $OutputDirectory 'manifest_log.jsonl'
    $singleLine = $Manifest | ConvertTo-Json -Depth 8 -Compress
    Add-Content -Path $rollingPath -Value $singleLine -Encoding UTF8
    Write-Host "Rolling manifest log:    $rollingPath" -ForegroundColor Cyan

    return $perGenPath
}

function Update-ManifestExecution {
    <#
        After running the generated script, update the per-generation manifest
        with execution results. The rolling log gets a second record appended
        so you can trace the full lifecycle (generate -> run -> result).
    #>
    param(
        [Parameter(Mandatory)] [string]$ManifestPath,
        [Parameter(Mandatory)] [string]$RollingLogPath,
        [Parameter(Mandatory)] [bool]$Executed,
        [Parameter()]          [int]$ExitCode = 0,
        [Parameter()]          [double]$DurationSeconds = 0
    )

    if (-not (Test-Path -Path $ManifestPath)) {
        Write-Host "WARNING: Manifest not found at $ManifestPath; cannot update execution result." -ForegroundColor Yellow
        return
    }

    $manifest = Get-Content -Path $ManifestPath -Raw | ConvertFrom-Json

    $manifest.Execution.Executed        = $Executed
    $manifest.Execution.ExitCode        = $ExitCode
    $manifest.Execution.DurationSeconds = $DurationSeconds
    $manifest.Execution.TimestampUtc    = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')

    $manifest | ConvertTo-Json -Depth 8 | Out-File -FilePath $ManifestPath -Encoding UTF8 -Force

    # Append the updated record to the rolling log too
    $singleLine = $manifest | ConvertTo-Json -Depth 8 -Compress
    Add-Content -Path $RollingLogPath -Value $singleLine -Encoding UTF8
}

