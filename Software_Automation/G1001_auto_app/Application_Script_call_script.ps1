function Read-CategoryOrNone {
    param([string]$Label, [string]$Default)
    while ($true) {
        $effectiveDefault = if ([string]::IsNullOrWhiteSpace($Default)) { '<none>' } else { $Default }
        $raw = Read-Host -Prompt "$Label [default: $effectiveDefault] (or 'exit' to cancel)"
        if (Test-ExitRequest $raw) { $script:exitRequested = $true; return $null }
        if ($raw -match '^(?i)none$') { return ,@() }
        if ([string]::IsNullOrWhiteSpace($raw)) {
            if ([string]::IsNullOrWhiteSpace($Default)) { return ,@() }
            $raw = $Default
        }
        $tokens = $raw -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ -ne '' }
        $parsed = @()
        $allValid = $true
        foreach ($tok in $tokens) {
            $n = 0
            if ([int]::TryParse($tok, [ref]$n)) { $parsed += $n }
            else {
                Write-Host "Invalid exit code '$tok'. Must be an integer." -ForegroundColor Yellow
                $allValid = $false; break
            }
        }
        if (-not $allValid) { continue }
        $unique = @()
        foreach ($n in $parsed) { if ($unique -notcontains $n) { $unique += $n } }
        return ,$unique
    }
}

function Resolve-ExitCodes {
    <#
        Resolve a single exit-code category. If config provides the key, validate
        and return its value. Otherwise fall through to interactive prompt.
    #>
    param(
        [Parameter(Mandatory)] [string]$ConfigKey,
        [Parameter(Mandatory)] [string]$Label,
        [Parameter()]          [string]$Default,
        [Parameter(Mandatory)] [hashtable]$Cfg
    )
    if ($Cfg.ContainsKey($ConfigKey)) {
        $raw = $Cfg[$ConfigKey]
        if ($null -eq $raw) { return ,@() }
        $arr = @($raw)
        $out = @()
        foreach ($n in $arr) {
            $i = 0
            if (-not [int]::TryParse([string]$n, [ref]$i)) {
                throw "Config error: '$ConfigKey' contains non-integer value '$n'."
            }
            if ($out -notcontains $i) { $out += $i }
        }
        Write-Host "$Label (from config) : $($out -join ', ')" -ForegroundColor DarkCyan
        return ,$out
    }
    return ,(Read-CategoryOrNone -Label $Label -Default $Default)
}

