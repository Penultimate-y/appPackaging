function ConvertTo-PsLiteral {
    <#
        Converts a PowerShell value into a source-code literal that, when pasted
        into a .ps1 file, recreates the original value. Handles strings, ints,
        and int arrays — which covers everything the orchestrator collects.
    #>
    param([Parameter()] $Value)

    if ($null -eq $Value) { return '$null' }

    if ($Value -is [System.Array]) {
        if ($Value.Count -eq 0) { return '@()' }
        $items = $Value | ForEach-Object { ConvertTo-PsLiteral $_ }
        return '@(' + ($items -join ', ') + ')'
    }

    if ($Value -is [int] -or $Value -is [long]) {
        return $Value.ToString()
    }

    $s = [string]$Value
    $escaped = $s -replace "'", "''"
    return "'$escaped'"
}

function Get-SafeFileNameSegment {
    param([string]$Value)
    if ([string]::IsNullOrWhiteSpace($Value)) { return 'unknown' }
    $cleaned = $Value -replace '[<>:"/\\|\?\*]', ''
    $cleaned = $cleaned -replace '\s+', '_'
    $cleaned = $cleaned.Trim('_', '.')
    if ([string]::IsNullOrWhiteSpace($cleaned)) { return 'unknown' }
    return $cleaned
}

function New-StandaloneDeploymentScript {
    <#
        Reads the parameterized template, strips its Param() block, injects the
        user's values as hardcoded variables, and saves the result as a new
        standalone .ps1 file. Returns the full path to the saved file.
    #>
    param(
        [Parameter(Mandatory)] [string]         $TemplatePath,
        [Parameter(Mandatory)] [string]         $OutputDirectory,
        [Parameter(Mandatory)] [PSCustomObject] $UserInput
    )

    if (-not (Test-Path -Path $TemplatePath)) {
        throw "Template script not found at: $TemplatePath"
    }

    $templateContent = Get-Content -Path $TemplatePath -Raw

    $paramBlockPattern = '(?ims)^\s*(\[CmdletBinding\(\)\]\s*)?Param\s*\((?:[^()]|\([^()]*\))*\)\s*'
    if ($templateContent -match $paramBlockPattern) {
        $templateContent = [System.Text.RegularExpressions.Regex]::Replace(
            $templateContent, $paramBlockPattern, '', 'IgnoreCase, Multiline, Singleline'
        )
    }
    else {
        Write-Host "WARNING: No Param() block found in template — values will be prepended without removal." -ForegroundColor Yellow
    }

    $generatedAt = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
    $valuesBlock = @"
##================================================
## MARK: Auto-Generated Hardcoded Values
##================================================
# Generated by orchestrator on $generatedAt
# Source template: $TemplatePath
# DO NOT EDIT BELOW — values are baked in from the orchestrator run.

`$applicationName = $(ConvertTo-PsLiteral $UserInput.AppName)
`$packageName     = $(ConvertTo-PsLiteral $UserInput.PackageName)
`$appVersion      = $(ConvertTo-PsLiteral $UserInput.AppVersion)
`$DeploymentType  = $(ConvertTo-PsLiteral $UserInput.DeploymentType)
`$installerType   = $(ConvertTo-PsLiteral $UserInput.InstallerType)
`$installerName   = $(ConvertTo-PsLiteral $UserInput.InstallerName)
`$arguments       = $(ConvertTo-PsLiteral $UserInput.Arguments)
`$successCodes    = $(ConvertTo-PsLiteral $UserInput.CombinedSuccessCodes)
`$retryCodes      = $(ConvertTo-PsLiteral $UserInput.RetryCodes)
`$processToStop   = $(ConvertTo-PsLiteral $UserInput.ProcessesToStop)
`$detectionPath   = $(ConvertTo-PsLiteral $UserInput.DetectionPath)

##================================================

"@

    $finalContent = $valuesBlock + $templateContent.TrimStart()

    $safeApp     = Get-SafeFileNameSegment $UserInput.AppName
    $safeVersion = Get-SafeFileNameSegment $UserInput.AppVersion
    $safeType    = Get-SafeFileNameSegment $UserInput.DeploymentType
    $baseName    = "Deploy_${safeApp}_${safeVersion}_${safeType}"
    $outputFile  = Join-Path $OutputDirectory "$baseName.ps1"

    if (Test-Path -Path $outputFile) {
        $timestamp  = Get-Date -Format 'yyyyMMdd_HHmmss'
        $outputFile = Join-Path $OutputDirectory "${baseName}_${timestamp}.ps1"
    }

    if (-not (Test-Path -Path $OutputDirectory)) {
        New-Item -Path $OutputDirectory -ItemType Directory -Force | Out-Null
    }

    $finalContent | Out-File -FilePath $outputFile -Encoding UTF8 -Force

    return $outputFile
}

