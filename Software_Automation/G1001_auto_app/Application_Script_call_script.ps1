function Import-DeploymentConfig {
    <#
        Load a JSON config file and return a hashtable of its values.
        Validates the file exists and parses cleanly. Field-level validation
        happens later when each value is consumed by the prompt logic.
    #>
    param([Parameter(Mandatory)] [string]$Path)

    if (-not (Test-Path -Path $Path)) {
        throw "Config file not found: $Path"
    }

    try {
        $raw = Get-Content -Path $Path -Raw -ErrorAction Stop
        $obj = $raw | ConvertFrom-Json -ErrorAction Stop
    }
    catch {
        throw "Failed to parse config file '$Path': $_"
    }

    # Convert the PSCustomObject from ConvertFrom-Json into a hashtable
    # so we can use ContainsKey() checks naturally.
    $hash = @{}
    foreach ($prop in $obj.PSObject.Properties) {
        $hash[$prop.Name] = $prop.Value
    }
    return $hash
}

function Get-ConfigValue {
    <#
        Pull a value from the config hashtable if present and non-null/non-empty.
        Returns $null if the key is missing or the value is empty — caller treats
        $null as "fall through to interactive prompt".
    #>
    param(
        [Parameter(Mandatory)] [hashtable]$Config,
        [Parameter(Mandatory)] [string]$Key
    )
    if (-not $Config.ContainsKey($Key)) { return $null }
    $v = $Config[$Key]
    if ($null -eq $v) { return $null }
    if ($v -is [string] -and [string]::IsNullOrWhiteSpace($v)) { return $null }
    return $v
}

function Save-DeploymentConfig {
    <#
        Serialize the collected $userInput object to a JSON config file the
        user can edit and re-feed via -ConfigFile.
    #>
    param(
        [Parameter(Mandatory)] [PSCustomObject]$UserInput,
        [Parameter(Mandatory)] [string]$Path
    )

