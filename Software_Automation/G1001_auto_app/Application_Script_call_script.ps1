function New-DeploymentManifest {
    <#
        Build a manifest object describing this deployment generation.
        Returns a PSCustomObject ready to be written to JSON.
    #>
    param(
        [Parameter(Mandatory)] [PSCustomObject]$UserInput,
        [Parameter(Mandatory)] [string]$GeneratedScriptPath,
        [Parameter()]          [string]$ConfigFilePath,
        [Parameter()]          [string]$InputSource = 'Interactive'
    )

    $now = Get-Date
    $hash = Get-FileSha256 -Path $GeneratedScriptPath
    $size = if (Test-Path -Path $GeneratedScriptPath) {
        (Get-Item -Path $GeneratedScriptPath).Length
    } else { 0 }

    $manifest = [ordered]@{
        Generation = [ordered]@{
            TimestampUtc        = $now.ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
            TimestampLocal      = $now.ToString('yyyy-MM-dd HH:mm:ss zzz')
            GeneratedBy         = "$env:USERDOMAIN\$env:USERNAME"
            GeneratedOn         = $env:COMPUTERNAME
            OrchestratorVersion = $script:OrchestratorVersion
            PowerShellVersion   = $PSVersionTable.PSVersion.ToString()
            OsVersion           = [System.Environment]::OSVersion.VersionString
            InputSource         = $InputSource
            ConfigFilePath      = $ConfigFilePath
        }
        Inputs = [ordered]@{
            AppName              = $UserInput.AppName
            PackageName          = $UserInput.PackageName
            AppVersion           = $UserInput.AppVersion
            DeploymentType       = $UserInput.DeploymentType
            InstallerType        = $UserInput.InstallerType
            InstallerName        = $UserInput.InstallerName
            Arguments            = $UserInput.Arguments
            ProcessesToStop      = @($UserInput.ProcessesToStop)
            DetectionPath        = $UserInput.DetectionPath
            SuccessCodes         = @($UserInput.SuccessCodes)
            SoftRebootCodes      = @($UserInput.SoftRebootCodes)
            HardRebootCodes      = @($UserInput.HardRebootCodes)
            RetryCodes           = @($UserInput.RetryCodes)
            CombinedSuccessCodes = @($UserInput.CombinedSuccessCodes)
        }
        GeneratedScript = [ordered]@{
            Path      = $GeneratedScriptPath
            Sha256    = $hash
            SizeBytes = $size
        }
        Execution = [ordered]@{
            Executed         = $false
            ExitCode         = $null
            DurationSeconds  = $null
            TimestampUtc     = $null
        }
    }

    return [PSCustomObject]$manifest
