        PackageName     = $UserInput.PackageName
        AppVersion      = $UserInput.AppVersion
        DeploymentType  = $UserInput.DeploymentType
        InstallerType   = $UserInput.InstallerType
        InstallerName   = $UserInput.InstallerName
        Arguments       = $UserInput.Arguments
        ProcessesToStop = @($UserInput.ProcessesToStop)
        DetectionPath   = $UserInput.DetectionPath
